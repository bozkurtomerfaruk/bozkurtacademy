export function registerStrings(){
  const target = window.BA?.translations;
  if(!target) return;
  for(const lang of Object.keys(strings)){
    target[lang] = target[lang] || {};
    Object.assign(target[lang], strings[lang]);
  }
}

export const t = (key) => window.BA?.t(key) || strings.tr[key] || key;
export const lang = () => window.BA?.lang || 'tr';
