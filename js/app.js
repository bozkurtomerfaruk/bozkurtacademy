let currentLang = localStorage.getItem('baLang') || 'tr';

function t(key){
  return translations[currentLang]?.[key] || translations.tr[key] || key;
}

function applyLanguage(lang){
  currentLang = lang;
  localStorage.setItem('baLang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(translations[lang] && translations[lang][key]) el.textContent = translations[lang][key];
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el=>{
    const value=translations[lang]?.[el.getAttribute('data-i18n-aria')];
    if(value) el.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    const key = el.getAttribute('data-i18n-placeholder');
    if(translations[lang] && translations[lang][key]) el.setAttribute('placeholder', translations[lang][key]);
  });
  document.querySelectorAll('.lang button').forEach(b=>{
    b.classList.toggle('active', b.dataset.lang===lang);
    b.setAttribute('aria-pressed', String(b.dataset.lang===lang));
  });
  window.dispatchEvent(new CustomEvent('ba:languagechange', {detail:{lang}}));
}

const BA_PAGES = ['home','lessons','grammar','exercises','exams','about','contact'];

function pageFromHash(){
  const raw=(location.hash || '#home').slice(1).split('/')[0];
  return BA_PAGES.includes(raw) ? raw : 'home';
}

function writePageHistory(page, mode='push'){
  if(!history.pushState) return;
  const state={baPage:page};
  if(mode==='replace') history.replaceState(state, '', '#'+page);
  else if(mode==='push') history.pushState(state, '', '#'+page);
}

function showPage(page, options={}){
  const {historyMode='push', scroll=true} = options;
  document.querySelectorAll('.page').forEach(p=>p.classList.remove('active'));
  const target = document.getElementById('page-'+page);
  if(target) target.classList.add('active');
  document.querySelectorAll('.nav-link').forEach(b=>{
    const current=b.dataset.page===page;
    b.classList.toggle('active', current);
    if(current) b.setAttribute('aria-current','page'); else b.removeAttribute('aria-current');
  });
  if(historyMode!=='none') writePageHistory(page, historyMode);
  if(scroll) window.scrollTo({top:0, behavior:'smooth'});
  window.dispatchEvent(new CustomEvent('ba:pagechange', {detail:{page}}));
}

